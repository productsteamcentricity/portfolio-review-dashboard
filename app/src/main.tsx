// Entry point of the new application (CR-0006). Bundled by scripts/build.mjs into one offline HTML file.
// Reads the build-info data block (a non-executable JSON <script>, parsed with JSON.parse) into a BuildStamp, builds
// the store over the browser wiring and the browser's preferences, and mounts the shell.

import { render } from 'preact';
import type { BuildStamp } from './model/review.ts';
import type { LogoAsset } from './ui/wiring.ts';
import { App, type BuildInfo } from './ui/App.tsx';
import { browserWiring } from './ui/wiring.ts';
import { createStore } from './ui/store.ts';
import { browserPrefs } from './services/storage.ts';
import { chartLib } from './ui/chart-lib.ts';

function readBuildInfo(): BuildInfo | null {
  const el = document.getElementById('build-info');
  if (!el || !el.textContent) return null;
  try {
    return JSON.parse(el.textContent) as BuildInfo;
  } catch {
    return null;
  }
}

/** The build stamp: the build id falls back to "unknown" and the channel to "preview" (never "release" by default). */
export function stampOf(info: BuildInfo | null): BuildStamp {
  const libs = Array.isArray(info?.libraries) ? info.libraries : [];
  return {
    buildId: typeof info?.buildId === 'string' && info.buildId !== '' ? info.buildId : 'unknown',
    channel: info?.channel === 'release' ? 'release' : 'preview',
    libraries: libs.map((l) => ({ name: String(l.name), version: String(l.version), sha256: typeof l.sha256 === 'string' ? l.sha256 : null })),
  };
}

// The built-in logos (app/src/config/brand-logos.json, generated by scripts/vendor-extract.mjs) join here once that
// file is in the tree: `logos = builtInLogos(brand.logos)` (views/logo.ts). Until then the logo is uploaded only.
const logos: LogoAsset[] = [];

const root = document.getElementById('app');
if (root) {
  const build = stampOf(readBuildInfo());
  const store = createStore({ wiring: browserWiring(build), prefs: browserPrefs(), logos });
  render(<App build={build} store={store} logos={logos} chart={chartLib} />, root);
  root.dataset['ready'] = 'true';
}
